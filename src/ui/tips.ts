/** 직전과 다른 팁을 하나 고른다(연속 중복 방지). */
export function nextTip(prev?: string, rand: () => number = Math.random): string {
  if (TIPS.length <= 1) return TIPS[0] ?? ''
  let t = TIPS[Math.floor(rand() * TIPS.length)] ?? TIPS[0]!
  let guard = 0
  while (t === prev && guard++ < 8) t = TIPS[Math.floor(rand() * TIPS.length)] ?? TIPS[0]!
  return t
}
